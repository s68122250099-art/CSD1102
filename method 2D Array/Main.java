
public class Main {
// ประกาศคลาสชื่อ Main เพื่อใช้เป็นคลาสหลักของโปรแกรมนี้

    public static void main(String[] args) {
        // เมธอด main เป็นจุดเริ่มต้นของการทำงานของโปรแกรม Java

        // 1. ประกาศตัวแปร int[][] ที่มีขนาด 10× 10 เพื่อใช้เก็บข้อมูลตัวเลขจำนวนเต็ม
        int[][] array1 = new int[10][10];

        // 2. method สำหรับ สุ่มค่าตัวเลขจำนวนเต็มระหว่าง 50 – 59 แล้วนำไปเก็บลงในทุกตำแหน่งของ 2D Array
        randomArray(array1);

        // 3. method สำหรับแสดงค่าข้อมูลทั้งหมดใน 2DArray โดยแสดงผลเป็นลักษณะตาราง
        System.out.println("Array 1");
        // แสดงข้อความบอกว่ากำลังแสดงข้อมูลของอาเรย์ตัวที่ 1
        displayArray(array1);
        // เรียกเมธอด displayArray เพื่อแสดงข้อมูลของ array1 ออกมาเป็นตาราง

        // 4.  ประกาศ 2D Array ขนาด 10 × 10 อีก 1 ตัว 
        int[][] array2 = new int[10][10];
        randomArray(array2);
        System.out.println("Array 2");
        displayArray(array2);
        // จากนั้นเขียน method เพื่อ บวกค่าของ array ทั้งสองตัวในตำแหน่งเดียวกัน และเก็บผลลัพธ์ลงใน array ใหม่
        int[][] result = addArray(array1, array2);
        // เรียกเมธอด addArray เพื่อบวกค่า array1 และ array2 แล้วเก็บผลลัพธ์ไว้ใน result
        System.out.println("Result");
        // แสดงข้อความบอกว่ากำลังแสดงผลลัพธ์จากการบวกอาเรย์
        displayArray(result);
        // แสดงข้อมูลของอาเรย์ result ที่ได้จากการบวกค่า
    }
    // ปิดเมธอด main

    public static void randomArray(int[][] arr) {
        // เมธอดนี้ใช้สำหรับสุ่มค่าตัวเลขแล้วนำไปเก็บในอาเรย์ที่รับเข้ามา
        for (int i = 0; i < arr.length; i++) {
            // วนลูปตามจำนวนแถวของอาเรย์
            for (int j = 0; j < arr[i].length; j++) {
                // วนลูปตามจำนวนคอลัมน์ของแต่ละแถว
                arr[i][j] = (int) (Math.random() * 10) + 50;
                // สุ่มค่าตัวเลขระหว่าง 50 ถึง 59 แล้วเก็บลงในตำแหน่ง [i][j]
            }
            // จบการวนลูปคอลัมน์
        }
        // จบการวนลูปแถว
    }
    // ปิดเมธอด randomArray

    public static void displayArray(int[][] arr) {
        // เมธอดนี้ใช้สำหรับแสดงค่าข้อมูลทั้งหมดในอาเรย์ 2 มิติ
        for (int i = 0; i < arr.length; i++) {
            // วนลูปแสดงข้อมูลทีละแถว
            for (int j = 0; j < arr[i].length; j++) {
                // วนลูปแสดงข้อมูลในแต่ละคอลัมน์ของแถวนั้น
                System.out.print(arr[i][j] + " ");
                // แสดงค่าตัวเลขในแต่ละตำแหน่งโดยไม่ขึ้นบรรทัดใหม่
            }
            // จบการแสดงข้อมูลในหนึ่งแถว
            System.out.println();
            // ขึ้นบรรทัดใหม่เมื่อแสดงข้อมูลครบหนึ่งแถว
        }
        // จบการแสดงข้อมูลทุกแถว
        System.out.println();
        // เว้นบรรทัดเพื่อให้ดูผลลัพธ์ง่ายขึ้น
    }
    // ปิดเมธอด displayArray

    public static int[][] addArray(int[][] arr1, int[][] arr2) {
        // เมธอดนี้ใช้สำหรับบวกค่าของอาเรย์ 2 มิติ สองตัวเข้าด้วยกัน
        int[][] result = new int[10][10];
        // สร้างอาเรย์ใหม่เพื่อใช้เก็บค่าผลลัพธ์จากการบวก
        for (int i = 0; i < arr1.length; i++) {
            // วนลูปตามจำนวนแถวของอาเรย์
            for (int j = 0; j < arr1[i].length; j++) {
                // วนลูปตามจำนวนคอลัมน์ของแต่ละแถว
                result[i][j] = arr1[i][j] + arr2[i][j];
                // นำค่าของ arr1 และ arr2 ในตำแหน่งเดียวกันมาบวกกัน
            }
            // จบการวนลูปคอลัมน์
        }
        // จบการวนลูปแถว
        return result;
        // ส่งค่าอาเรย์ผลลัพธ์กลับไปยังเมธอด main
    }
    // ปิดเมธอด addArray
}
// ปิดคลาส Main
